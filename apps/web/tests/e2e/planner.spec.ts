test("unsupported saved snapshots require an explicit new plan", async ({page}) => {
  await page.route("**/api/plan",route => route.fulfill({status:409,contentType:"application/json",body:JSON.stringify({error:"unsupported_state"})}));
  let creates = 0;
  page.on("request", request => {if (request.url().endsWith("/api/session") && request.method() === "POST") creates++;});
  await page.goto("/");
  await expect(page.getByRole("alert")).toContainText("舊餐單格式");
  expect(creates).toBe(0);
  await page.getByRole("button",{name:"開始新規劃"}).click();
  await expect(page.getByText("目前為唯讀狀態。")).toHaveCount(0);
  await expect(page.getByRole("button",{name:"清除本次規劃"})).toBeVisible();
  expect(creates).toBe(1);
});

for (const recovery of ["reload","conflict"] as const) {
  test(`${recovery} synchronizes goal and preferences from the recovered snapshot`, async ({page}) => {
    await page.goto("/");
    await page.getByRole("button",{name:"載入合成目標"}).click();
    await page.getByRole("button",{name:"確認使用此目標"}).click();
    await page.getByRole("button",{name:"產生三天提案"}).click();
    await page.getByRole("button",{name:"採用這份提案"}).click();
    const adopted = page.getByRole("region",{name:"已採用餐單"});
    await expect(adopted).toContainText("已保存 · 版本 1");
    const remote = await page.evaluate(async () => (await fetch("/api/plan")).json());
    remote.revision = 2;
    remote.current.candidate.goal.requested.kcal = 1800;
    remote.current.candidate.goal.ranges.kcal = {min:1710,max:1890};
    remote.current.candidate.constraints.preferredFoods = ["oats"];
    remote.current.candidate.constraints.slots = ["lunch"];
    remote.current.candidate.constraints.equipment = ["pot"];
    await page.route("**/api/plan",route => route.fulfill({json:remote}));
    if (recovery === "reload") await page.getByRole("button",{name:"重新讀取餐單"}).click();
    else {
      await page.route("**/api/plan/actions",route => route.fulfill({status:409,json:{error:"revision_conflict"}}));
      await adopted.getByRole("button",{name:"鎖定",exact:true}).first().click();
    }
    await expect(adopted).toContainText("已保存 · 版本 2");
    await page.getByText("生活條件、固定餐點與庫存",{exact:true}).click();
    let goal: unknown;
    await page.route("**/api/plan/preview",route => {goal = route.request().postDataJSON().goal;return route.fulfill({status:503,json:{error:"calculation_unavailable"}});});
    await page.getByRole("button",{name:"產生三天提案"}).click();
    await expect(page.getByRole("alert")).toContainText("提案未完成");
    expect(goal).toMatchObject({requested:{kcal:1800}});
    await expect(page.getByLabel("早餐",{exact:true})).not.toBeChecked();
    await expect(page.getByLabel("鍋具",{exact:true})).toBeChecked();
    await expect(page.getByLabel("偏好食材（逗號分隔）")).toHaveValue(/oats|燕麥/);

  });
}

test("Chinese food exclusions resolve to catalog identifiers before preview", async ({page}) => {
  await page.goto("/");
  await page.getByRole("button",{name:"載入合成目標"}).click();
  await page.getByRole("button",{name:"確認使用此目標"}).click();
  await page.getByLabel("排除食材（逗號分隔）").fill("燕麥");
  let excluded: unknown;
  await page.route("**/api/plan/preview",route => {excluded = route.request().postDataJSON().constraints.excludedFoods;return route.fulfill({status:503,json:{error:"calculation_unavailable"}});});
  await page.getByRole("button",{name:"產生三天提案"}).click();
  await expect(page.getByRole("alert")).toContainText("提案未完成");
  expect(excluded).toEqual(["oats"]);
  excluded = undefined;
  await page.getByLabel("排除食材（逗號分隔）").fill("尚未收錄的食材");
  await page.getByRole("button",{name:"產生三天提案"}).click();
  await expect(page.getByRole("alert").filter({hasText:"無法確認食材"})).toBeVisible();
  expect(excluded).toBeUndefined();
});

