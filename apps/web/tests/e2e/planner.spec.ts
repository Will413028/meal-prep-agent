import { expect, test } from "@playwright/test";

test("manual goal creates a preview, adopts a plan, replaces one meal and reopens the saved revision", async ({page}) => {
  await page.goto("/");
  await page.getByLabel("每日熱量（kcal）").fill("2000");
  await page.getByLabel("每日蛋白質（g）").fill("100");
  await page.getByRole("button",{name:"檢查目標"}).click();
  await page.getByRole("button",{name:"確認使用此目標"}).click();
  await expect(page.getByRole("region",{name:"安排三天餐單"})).toBeVisible();
  await page.getByLabel("開始日期").fill("2026-10-01");
  await page.getByRole("button",{name:"產生三天提案"}).click();
  const preview = page.getByRole("region",{name:"餐單提案預覽"});
  await expect(preview).toBeVisible();
  await expect(page.getByRole("region",{name:"已採用餐單"})).toHaveCount(0);
  await page.getByRole("button",{name:"採用這份提案"}).click();
  const adopted = page.getByRole("region",{name:"已採用餐單"});
  await expect(adopted).toContainText("已保存 · 版本 1");
  await expect(preview).toHaveCount(0);
  await expect(page.getByRole("region",{name:"採買清單"})).toBeVisible();
  await adopted.getByRole("button",{name:"換菜"}).first().click();
  await expect(preview).toBeVisible();
  await expect(adopted).toContainText("已保存 · 版本 1");
  await page.getByRole("button",{name:"取消提案"}).click();
  await expect(preview).toHaveCount(0);
  await adopted.getByRole("button",{name:"換菜"}).first().click();
  await page.getByRole("button",{name:"採用這份提案"}).click();
  await expect(adopted).toContainText("已保存 · 版本 2");
  const meals = await adopted.getByTestId("meal-name").allTextContents();
  await page.reload();
  await expect(adopted).toContainText("已保存 · 版本 2");
  expect(await adopted.getByTestId("meal-name").allTextContents()).toEqual(meals);
  const portion = adopted.getByLabel("2026-10-01 早餐份量");
  const quantity = await portion.inputValue() === "1.5" ? "1.25" : "1.5";
  await portion.fill(quantity);
  await adopted.getByRole("button",{name:"更新份量"}).first().click();
  await expect(adopted).toContainText("已保存 · 版本 3");
  await expect(adopted.getByRole("article").first()).toContainText(quantity === "1.25" ? "本餐熱量：500 kcal" : "本餐熱量：600 kcal");
  await adopted.getByRole("button",{name:"鎖定",exact:true}).first().click();
  await expect(adopted).toContainText("已保存 · 版本 4");
  const shopping = adopted.getByRole("region",{name:"採買清單"}).getByRole("checkbox").first();
  await shopping.click();
  await expect(adopted).toContainText("已保存 · 版本 5");
  await adopted.getByRole("button",{name:"復原上一版"}).click();
  await expect(adopted).toContainText("已保存 · 版本 6");
  await expect(shopping).not.toBeChecked();
  await page.route("**/api/plan/actions",route => route.fulfill({status:503,json:{error:"storage_unavailable"}}));
  await page.route("**/api/plan",route => route.fulfill({status:503,json:{error:"storage_unavailable"}}));
  await shopping.click();
  await expect(adopted).toContainText("唯讀快照 · 版本 6");
  await expect(shopping).not.toBeChecked();
  await expect(shopping).toBeDisabled();
  await page.unroute("**/api/plan/actions");await page.unroute("**/api/plan");
  await page.getByRole("button",{name:"重新讀取餐單"}).click();
  await expect(adopted).toContainText("已保存 · 版本 6");
  await page.route("**/api/plan/preview",route => route.fulfill({status:503,json:{error:"calculation_unavailable"}}));
  await adopted.getByRole("button",{name:"換菜"}).nth(1).click();
  await expect(page.getByRole("alert")).toContainText("提案未完成");
  await shopping.click();
  await expect(adopted).toContainText("已保存 · 版本 7");
  await page.route("**/api/session",route => route.fulfill({status:503,json:{error:"storage_unavailable"}}));
  await page.route("**/api/plan",route => route.fulfill({status:503,json:{error:"storage_unavailable"}}));
  await page.getByRole("button",{name:"清除本次規劃"}).click();
  await expect(adopted).toContainText("唯讀快照 · 版本 7");
  await expect(page.getByRole("alert")).toContainText("清除尚未確認");
  await page.unroute("**/api/session");await page.unroute("**/api/plan");
  await page.getByRole("button",{name:"清除本次規劃"}).click();
  await expect(adopted).toHaveCount(0);
  await page.reload();
  await expect(adopted).toHaveCount(0);
});

